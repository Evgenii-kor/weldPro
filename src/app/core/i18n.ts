export type I18nKey = keyof typeof ru;
const DICT: Record<Lang, Record<I18nKey, string>> = { ru, en };

@Injectable({ providedIn: 'root' })
export class I18n {
  readonly lang = signal<Lang>('ru');

  set(lang: Lang): void {
    this.lang.set(lang);
  }

  t(key: I18nKey): string {
    return DICT[this.lang()][key];
  }

  /** Выбор строки нужного языка из локализованного объекта. */
  loc(v: Localized): string {
    return v[this.lang()];
  }

  /** Сегменты роутера с языковым префиксом: path('catalog') → ['/ru','catalog'] */
  link(...segments: string[]): string[] {
    return ['/' + this.lang(), ...segments];
  }

  money(n: number): string {
    return new Intl.NumberFormat(this.lang() === 'ru' ? 'ru-RU' : 'en-US', {
      style: 'currency',
      currency: 'RUB',
      minimumFractionDigits: 0,
      maximumFractionDigits: 0,
    }).format(n);
  }
}
